    /**
     * @return list<string>
     */
    public static function genres(int $count): array
    {
        $genres = self::GENRES;
        shuffle($genres);

        return array_slice($genres, 0, max(1, min($count, count($genres))));
    }

    /**
     * @param  list<string>  $values
     */
    private static function random(array $values): string
    {
        return $values[array_rand($values)];
